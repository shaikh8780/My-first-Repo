// AI content provenance (compliance requirement, 2026-07-09 call — Zuzana/DDIT).
//
// The system MUST differentiate AI-generated/modified content from human content,
// show a REASON for each AI modification, and capture explicit reviewer consent
// that the AI content was reviewed. This module is the source of truth for WHICH
// paragraphs of a subsection are AI-authored and WHY.
//
// Model: per subsection, a map of paragraph index → provenance entry. A paragraph
// with no entry is treated as human-authored. When an AI-origin tracked change is
// accepted into the content, EditorView records the new paragraph's provenance
// here. Demo state is localStorage-backed via EditorView; seeded so the
// highlighting + consent flow is visible out of the box.

export interface AiProvenanceEntry {
  reason: string;          // why the AI generated/changed this paragraph
  model?: string;          // which model produced it (audit)
  at?: string;             // when
  kind: 'generated' | 'modified';
}

// subsectionId -> { paragraphIndex -> entry }
export type AiProvenanceMap = Record<string, Record<number, AiProvenanceEntry>>;

const MODEL = 'claude-sonnet-4-6 (Bedrock AgentCore)';

// Seed: the FY2026 first draft was AI-generated by roll-forward + augmentation, so
// several subsections carry AI-authored paragraphs with an explanation. Indices
// are paragraph positions within ReportSection.content (split on "\n\n").
export const initialAiProvenance: AiProvenanceMap = {
  // Climate strategy and roadmap — draft generated from prior-year + SBTi data.
  'sub-8-1-3': {
    0: { kind: 'generated', model: MODEL, at: '2026-03-15T09:45:00Z', reason: 'Generated from the FY2025 approved transition-plan narrative (roll-forward), refreshed with the SBTi-validated 2030/2040 targets from the knowledge base.' },
    1: { kind: 'generated', model: MODEL, at: '2026-03-15T09:45:00Z', reason: 'Drafted from FY2026 actuals in the knowledge base: carbon-neutrality achievement and Scope 3 reduction levers. Figures require human verification before sign-off.' },
  },
  // Health & safety IRO — generated from prior-year structure.
  'sub-9-1-1': {
    0: { kind: 'generated', model: MODEL, at: '2026-03-15T09:47:00Z', reason: 'Generated from the FY2025 Health & safety impacts/risks narrative (roll-forward); hazard list and HSE-system scope carried forward for human review.' },
  },
  // Business conduct — governance boilerplate generated + one modified paragraph.
  'sub-10-1': {
    0: { kind: 'generated', model: MODEL, at: '2026-03-15T09:50:00Z', reason: 'Generated from the Code of Ethics and anti-bribery policy documents in the knowledge base.' },
  },
};

// Merge in provenance for AI-rolled-forward subsections (built in
// reportSections.ts). These are the sections whose FY2026 first draft was
// produced by rolling the FY2025 approved narrative forward. Imported lazily via
// a spread so the hand-authored seeds above take precedence on any overlap.
import { rolledForwardProvenance } from './reportSections';

for (const [sectionId, entries] of Object.entries(rolledForwardProvenance)) {
  if (!initialAiProvenance[sectionId]) initialAiProvenance[sectionId] = entries;
}

export function provenanceFor(map: AiProvenanceMap, sectionId: string): Record<number, AiProvenanceEntry> {
  return map[sectionId] ?? {};
}

export function aiParagraphCount(map: AiProvenanceMap, sectionId: string): number {
  return Object.keys(provenanceFor(map, sectionId)).length;
}
